source(file.path("r", "acquisisci_nuove_gare.R"))
stopifnot(inherits(try(scarica_nuove_gare_nba(as.character(Sys.Date()), 2027L), silent = TRUE), "try-error"))
storico <- data.frame(idGame = c("1", "2"), idPlayer = c("a", "b"), hustle = c(1, 2), stringsAsFactors = FALSE)
nuove <- data.frame(idGame = c("2", "3"), idPlayer = c("b", "c"), hustle = c(20, 30), stringsAsFactors = FALSE)
unito <- unisci_box_giocatori(storico, nuove)
stopifnot(nrow(unito) == 3L, unito$hustle[unito$idGame == "2"] == 20)
contenitore <- data.frame(typeResult = "player", stringsAsFactors = FALSE); contenitore$dataBoxScore <- I(list(storico))
file_storico <- tempfile(fileext = ".rds"); file_nuove <- tempfile(fileext = ".rds"); file_destinazione <- tempfile(fileext = ".rds")
saveRDS(contenitore, file_storico); saveRDS(nuove, file_nuove)
aggiorna_box_data_nba(file_storico, file_nuove, file_destinazione)
risultato <- readRDS(file_destinazione)
stopifnot(nrow(risultato) == 1L, nrow(risultato$dataBoxScore[[1L]]) == 3L)
stopifnot(risultato$dataBoxScore[[1L]]$hustle[risultato$dataBoxScore[[1L]]$idGame == "2"] == 20)
cartella <- tempfile("intervallo_")
player <- data.frame(idGame = c("g1", "g2", "g3"), idPlayer = c("p1", "p2", "p3"), dateGame = as.Date(c("2026-01-01", "2026-01-03", "2026-01-05")))
team <- data.frame(idGame = c("g1", "g2", "g3"), slugTeam = c("A", "B", "C"), dateGame = as.Date(c("2026-01-01", "2026-01-03", "2026-01-05")))
box <- data.frame(idGame = c("g1", "g2", "g3"), idPlayer = c("p1", "p2", "p3"))
lettore_log <- function(tipo) if (identical(tipo, "player")) player else team
intervallo <- scarica_intervallo_gare_nba("2026-01-02", "2026-01-04", 2026L, cartella, lettore_log, function(ids) box[box$idGame %in% ids, , drop = FALSE])
stopifnot(intervallo$ha_gare, identical(intervallo$idGame, "g2"), file.exists(file.path(cartella, "nuove_giocatori_2026-01-02_2026-01-04.rds")))
vuoto <- scarica_intervallo_gare_nba("2026-01-02", "2026-01-02", 2026L, tempfile("vuoto_"), lettore_log, function(ids) box[0, , drop = FALSE])
stopifnot(!vuoto$ha_gare)
cat("test_acquisisci_nuove_gare: OK\n")
