source(file.path("r", "esporta_modelli_calibrazione.R"))
tabella <- data.frame(fascia = c("bassa", "alta"), rmse = c(2, 4), correzione_q30 = c(-1, -3), bias = c(0.5, 1.5))
artefatto <- crea_artefatto_modello_calibrato(list(finto = TRUE), "pts", paste0("x", seq_len(40)), c(-Inf, 10, Inf), c("bassa", "alta"), tabella, "fascia", "rmse", "bias")
stopifnot(identical(artefatto$calibrazione_script$fasce$bias, c(0.5, 1.5)))
cartella <- tempfile("modelli_calibrati_")
configurazioni <- stats::setNames(replicate(7L, artefatto, simplify = FALSE), c("minuti", "punti", "rimbalzi", "assist", "punti_assist", "punti_rimbalzi", "rimbalzi_assist"))
percorsi <- pubblica_modelli_calibrazione(configurazioni, as.Date("2026-10-21"), cartella)
stopifnot(length(percorsi) == 7L, all(file.exists(percorsi)), all(grepl("2026-W43", percorsi, fixed = TRUE)))
stopifnot(file.exists(file.path(cartella, "features_2026-W43.rds")), file.exists(file.path(cartella, "features_2026-W43.csv")))
cat("test_esporta_modelli_calibrazione: OK\n")
